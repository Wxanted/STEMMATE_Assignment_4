// Builds js/app.bundle.js: one classic script so index.html also works when double-clicked (file://).
// Source of truth stays in the module files (data, logic, storage, auth, app). Run: node build.mjs
import { readFileSync, writeFileSync } from "node:fs";
const order = ["data", "logic", "storage", "auth", "app"];
let out = "// GENERATED by build.mjs - do not edit. Edit js/*.js then run: node build.mjs\n(function () {\n\"use strict\";\n";
for (const f of order) {
  const src = readFileSync(`js/${f}.js`, "utf8")
    .replace(/^import[^;]*;\s*$/gm, "")
    .replace(/^export\s+(?=(class|const|function|let)\b)/gm, "");
  out += `\n/* ---- ${f}.js ---- */\n` + src + "\n";
}
out += "\n})();\n";
writeFileSync("js/app.bundle.js", out);
console.log("wrote js/app.bundle.js", out.length, "bytes");
